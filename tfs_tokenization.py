def onehot_encode(seq, max_len):
    matrix = np.zeros((max_len, len(STANDARD_AAS)), dtype=np.float32)
    for i, aa in enumerate(seq[:max_len]):
        if aa in AA2IDX:
            matrix[i, AA2IDX[aa] - 1] = 1.0
    return matrix

